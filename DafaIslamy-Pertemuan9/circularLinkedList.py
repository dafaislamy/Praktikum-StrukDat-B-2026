'''
Advantage of Circular Linked List
1. Efficient Traversal
2. No Null Pointers / References
3. Useful for Repetitive Tasks
4. Insertion at Beginning or End is O(1)
5. Uniform Traversal
6. Efficient Memory Utilization

Disadvantage of Circular Linked List
1. Complex Implementation
2. Infinite Loop Risk
3. Harder to Debug
4. Deletion Complexity
5. Memory Overhead (for Doubly Circular LL)
6. Not Cache Friendly
'''